#!/bin/sh
# Fails unless third_party/apple_ca/AppleRootCA.pem has Apple's published SHA-256 and host/apple_root_ca.h was generated from it.
# With --write it regenerates the header first.
set -e
cd "$(dirname "$0")/.."
WANT=B0B1730ECBC7FF4505142C49F1295E6EDA6BCAED7E2C68C5BE91B5A11001F024
GOT=$(openssl x509 -in third_party/apple_ca/AppleRootCA.pem -noout -fingerprint -sha256 | cut -d= -f2 | tr -d : | tr a-f A-F)
[ "$GOT" = "$WANT" ] || { echo "Apple Root CA fingerprint mismatch: $GOT"; exit 1; }
gen() {
  echo "/* Generated by tools/check-apple-ca.sh --write from third_party/apple_ca/AppleRootCA.pem. Do not edit. */"
  echo "#define APPLE_ROOT_CA_SHA256 \"$(echo $WANT | tr A-F a-f)\""
  echo "static const char apple_root_ca_pem[] ="
  sed 's/.*/    "&\\n"/' third_party/apple_ca/AppleRootCA.pem
  echo "    ;"
}
if [ "${1:-}" = "--write" ]; then gen > host/apple_root_ca.h; fi
gen | cmp -s - host/apple_root_ca.h || { echo "host/apple_root_ca.h is not generated from the PEM (run tools/check-apple-ca.sh --write)"; exit 1; }
echo "Apple Root CA: fingerprint ok, header ok"
